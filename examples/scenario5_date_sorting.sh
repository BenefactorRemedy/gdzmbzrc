#!/bin/bash
# Сценарий 5: Сортировка по дате - Q5=YES

echo "╔══════════════════════════════════════════════════════════════╗"
echo "║  СЦЕНАРИЙ 5: Сортировка по дате - Q5=YES                    ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""
echo "📋 Описание:"
echo "   - 3 заказа одного приоритета (A) с разными датами"
echo "   - ORD001: 2026-03-01 (поздняя дата)"
echo "   - ORD002: 2026-02-15 (ранняя дата)"
echo "   - ORD003: 2026-02-20 (средняя дата)"
echo "   - Остаток: 100 единиц (недостаточно для всех)"
echo ""
echo "🎯 С Q5=YES:"
echo "   Заказы обрабатываются по датам (раньше → позже)"
echo "   ORD002 → ORD003 → ORD001"
echo ""
echo "⚙️  Параметры:"
echo "   Q5=YES (сортировка по дате)"
echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

python -m src.main \
  --q1 "ORD001|SKU-A|50|A|2026-03-01
ORD002|SKU-A|50|A|2026-02-15
ORD003|SKU-A|50|A|2026-02-20" \
  --q2 "SKU-A|100" \
  --q3 YES \
  --q5 YES

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "✅ Сценарий завершен!"
echo ""
echo "📊 Что проверить:"
echo "   ✓ ORD002 (2026-02-15) получил 50/50 (самая ранняя дата)"
echo "   ✓ ORD003 (2026-02-20) получил 50/50 (следующая дата)"
echo "   ✓ ORD001 (2026-03-01) получил 0/50 (поздняя дата)"
echo ""
echo "💡 Сравните с Q5=NO (FIFO):"
echo "   bash examples/scenario5_fifo.sh"
